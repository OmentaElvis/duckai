/**
 * Bundles src/injected → dist/inject.js (IIFE, document-start safe) and
 * emits src/generated/inject-script.ts exporting the source as a string so
 * `bun build --compile` embeds it in the binary.
 *
 * Usage: bun scripts/build-inject.ts [--minify]
 */
import { mkdir, writeFile } from "node:fs/promises";

const minify = process.argv.includes("--minify");

const result = await Bun.build({
  entrypoints: ["src/injected/index.ts"],
  outdir: "dist",
  format: "iife",
  target: "browser",
  minify,
  naming: "inject.js",
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

const js = await result.outputs[0]!.text();

await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/inject-script.ts",
  `// GENERATED by scripts/build-inject.ts — do not edit.\n` +
    `export const INJECT_SCRIPT = ${JSON.stringify(js)};\n`,
);

console.log(`inject built: ${js.length} chars (minify=${minify}) → dist/inject.js + src/generated/inject-script.ts`);
